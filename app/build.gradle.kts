    signingConfigs {
        create("release") {
            val keystorePropertiesFile = rootProject.file("keystore.properties")
            if (keystorePropertiesFile.exists()) {
                val keystoreProperties = Properties()
                keystorePropertiesFile.inputStream().use { stream ->
                    keystoreProperties.load(stream)
                }
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            } else if (System.getenv("KEYSTORE_STORE_FILE") != null) {
                storeFile = file(System.getenv("KEYSTORE_STORE_FILE"))
                storePassword = System.getenv("KEYSTORE_STORE_PASSWORD")
                keyAlias = System.getenv("KEYSTORE_KEY_ALIAS")
                keyPassword = System.getenv("KEYSTORE_KEY_PASSWORD")
            } else {
                throw GradleException("RELEASE SIGNING ERROR: Missing release signing credentials. Please create 'keystore.properties' (see keystore.properties.example) or set KEYSTORE_* environment variables.")
            }
        }
    }

